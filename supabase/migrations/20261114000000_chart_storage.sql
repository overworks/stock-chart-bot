create table public.chart_symbol_catalog (
  id text primary key check (id = 'symbols:v1'),
  entries jsonb not null check (jsonb_typeof(entries) = 'array')
);

create table public.chart_aliases (
  alias text primary key check (char_length(alias) between 1 and 40 and alias = btrim(alias)),
  symbol text not null check (symbol <> ''),
  position bigint generated by default as identity unique
);

create table public.chart_alias_requests (
  request_key text primary key,
  expires_at_ms bigint not null
);
create index chart_alias_requests_expiry on public.chart_alias_requests (expires_at_ms);

create table public.chart_token_cache (
  key text primary key check (key = 'kis:token:v1'),
  token text not null,
  token_expires_at_sec bigint not null,
  expires_at_ms bigint not null
);

alter table public.chart_symbol_catalog enable row level security;
alter table public.chart_aliases enable row level security;
alter table public.chart_alias_requests enable row level security;
alter table public.chart_token_cache enable row level security;

revoke all on public.chart_symbol_catalog, public.chart_aliases,
  public.chart_alias_requests, public.chart_token_cache from public, anon, authenticated;
grant select, insert, update, delete on public.chart_symbol_catalog, public.chart_aliases,
  public.chart_alias_requests, public.chart_token_cache to service_role;
revoke all on sequence public.chart_aliases_position_seq from public, anon, authenticated;
grant usage, select on sequence public.chart_aliases_position_seq to service_role;

create function public.read_chart_aliases()
returns jsonb
language sql stable security invoker
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object('key', alias, 'value', symbol) order by position), '[]'::jsonb)
  from public.chart_aliases;
$$;

create function public.mutate_chart_alias(
  p_key text,
  p_value text default null,
  p_request_key text default null,
  p_expires_at_ms bigint default null
)
returns jsonb
language plpgsql security invoker
set search_path = ''
as $$
declare
  v_now_ms bigint;
  v_recorded_expiry bigint;
  v_entry jsonb;
begin
  if p_key is null or char_length(p_key) not between 1 and 40 or p_key <> btrim(p_key)
    or p_value = '' or (p_request_key is null) <> (p_expires_at_ms is null) or p_request_key = '' then
    return jsonb_build_object('error', jsonb_build_object('status', 400, 'message', '별칭 변경 인자가 올바르지 않습니다.'));
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('stock-chart-bot'), pg_catalog.hashtext('aliases:v1'));
  v_now_ms := floor(extract(epoch from clock_timestamp()) * 1000)::bigint;
  if p_request_key is not null then
    if p_expires_at_ms <= v_now_ms then
      return jsonb_build_object('error', jsonb_build_object('status', 408, 'message', '별칭 변경 요청이 만료됐습니다. 다시 실행해 주세요.'));
    end if;
    select expires_at_ms into v_recorded_expiry
      from public.chart_alias_requests where request_key = p_request_key;
    if found then
      -- 중복 요청의 만료 연장도 커밋해야 하므로 예외 대신 결과를 반환한다.
      update public.chart_alias_requests set expires_at_ms = greatest(expires_at_ms, p_expires_at_ms)
        where request_key = p_request_key;
      return jsonb_build_object('error', jsonb_build_object('status', 409, 'message', '이미 처리한 별칭 변경 요청입니다.'));
    end if;
  end if;

  if p_value is null then
    delete from public.chart_aliases where alias = p_key
      returning jsonb_build_object('key', alias, 'value', symbol) into v_entry;
    if not found then
      return jsonb_build_object('error', jsonb_build_object('status', 404, 'message', format('''%s'' 별칭이 없습니다.', p_key)));
    end if;
  else
    insert into public.chart_aliases (alias, symbol) values (p_key, p_value)
      on conflict (alias) do update set symbol = excluded.symbol, position = excluded.position
      returning jsonb_build_object('key', alias, 'value', symbol) into v_entry;
  end if;

  if p_request_key is not null then
    insert into public.chart_alias_requests (request_key, expires_at_ms) values (p_request_key, p_expires_at_ms);
  end if;
  delete from public.chart_alias_requests where request_key in (
    select request_key from public.chart_alias_requests where expires_at_ms <= v_now_ms
      order by expires_at_ms limit 128
  );
  return jsonb_build_object('entry', v_entry);
end;
$$;

revoke execute on function public.read_chart_aliases() from public, anon, authenticated;
revoke execute on function public.mutate_chart_alias(text, text, text, bigint) from public, anon, authenticated;
grant execute on function public.read_chart_aliases() to service_role;
grant execute on function public.mutate_chart_alias(text, text, text, bigint) to service_role;

